import assert from 'node:assert/strict';
import { canDirect, canSupport, canViewAnnouncement, isOwner } from '../api/_wesalPolicy.mjs';
const user=(uid,role,schoolId='school-A',classId='class-1')=>({uid,email:uid+'@example.edu',role,approved:true,schoolId,classId});
const teacher=user('teacher-1','teacher');
const student=user('student-1','student');
const manager=user('manager-1','schoolAdmin');
const otherTeacher=user('teacher-2','teacher');
const otherStudent=user('student-2','student','school-B');
const owner={...user('owner-123','admin',undefined),email:'he4amali22@gmail.com'};
const classroom={id:'class-1',teacherId:'teacher-1'};
assert.equal(canDirect(teacher,student,classroom),true);
assert.equal(canDirect(student,teacher,classroom),true);
assert.equal(canDirect(manager,teacher,null),true);
assert.equal(canDirect(teacher,manager,null),true);
assert.equal(canDirect(otherTeacher,student,classroom),false,'Unassigned teachers cannot message a student');
assert.equal(canDirect(student,otherTeacher,classroom),false,'Students cannot message unrelated teachers');
assert.equal(canDirect(teacher,otherStudent,classroom),false,'Cross-school messaging is prohibited');
assert.equal(canDirect(teacher,{...student,approved:false},classroom),false);
assert.equal(canDirect({...teacher,schoolId:'__demo__'},student,classroom),false);
assert.equal(canDirect(student,student,classroom),false);
assert.equal(canSupport(manager,owner),true);
assert.equal(canSupport(owner,manager),true);
assert.equal(canSupport(student,owner),false);
assert.equal(canSupport(user('manager-2','schoolAdmin','__demo__'),owner),false);
assert.equal(isOwner({...owner,email:'attacker@example.edu'}),false);
assert.equal(canViewAnnouncement(teacher,{schoolId:'school-A',audience:'teachers'},null),true);
assert.equal(canViewAnnouncement(student,{schoolId:'school-A',audience:'teachers'},null),false);
assert.equal(canViewAnnouncement(student,{schoolId:'school-A',audience:'class',classId:'class-1'},classroom),true);
assert.equal(canViewAnnouncement(otherStudent,{schoolId:'school-A',audience:'class',classId:'class-1'},classroom),false);
assert.equal(canViewAnnouncement(otherTeacher,{schoolId:'school-A',audience:'class',classId:'class-1'},classroom),false);
assert.equal(canViewAnnouncement(manager,{schoolId:'school-A',audience:'class',classId:'class-1'},classroom),true);
console.log('Wesal policy regression checks passed.');
