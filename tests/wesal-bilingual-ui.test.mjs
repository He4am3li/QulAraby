import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (path) => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const view = read('components/Wesal.tsx');
const styles = read('components/wesal.css');
const glass = read('components/topBarGlass.css');
const home = read('pages/Home.tsx');
const top = read('components/PlatformTopBar.tsx');
const layout = read('components/Layout.tsx');
const toggle = read('components/LanguageToggle.tsx');

assert.match(view, /window\.addEventListener\('langChanged', syncLanguage\)/, 'Wesal must track live language changes');
assert.match(view, /window\.addEventListener\('storage', syncLanguage\)/, 'Cross-tab language changes must sync');
assert.match(view, /dir=\{lang === 'en' \? 'ltr' : 'rtl'\}/, 'Wesal dialog must use the selected text direction');
assert.match(view, /const tr = \(arabic: string, english: string\)/, 'Wesal must use bilingual strings');
assert.doesNotMatch(view, /className="wesal-monogram"/, 'No decorative letter badge in the header');
assert.match(view, /tr\('جاري تحميل المحادثة\.\.\.', 'Loading conversation\.\.\.'\)/);
assert.match(view, /tr\('نشر التعميم', 'Publish announcement'\)/);
assert.match(view, /tr\('عرض عدّاد الرسائل', 'Show unread count'\)/);
assert.match(view, /dir="auto" className=\{'wesal-bubble/, 'Messages preserve their authored language and direction');
assert.match(styles, /\.wesal-panel\[dir="ltr"\]\s*\{[^}]*right:14px;[^}]*left:auto;/, 'English must open from the opposite side');
assert.match(styles, /\.wesal-panel\[dir="ltr"\] \.wesal-main/, 'English content must mirror as well');
assert.match(styles, /@keyframes wesal-open-english/, 'Mirror the entrance animation');
assert.match(glass, /\.qul-header-glass\s*\{[^}]*width: 258px;/, 'Side clusters must have identical width');
assert.match(glass, /backdrop-filter: blur\(25px\) saturate\(150%\)/, 'Refined glass must have gentle optical depth');
assert.equal((home.match(/className="qul-header-glass/g)||[]).length, 2, 'Home should have two balanced glass clusters');
assert.equal((top.match(/className="qul-header-glass/g)||[]).length, 2, 'School and admin headers should have two balanced clusters');
assert.match(toggle, /qul-language-action/, 'Existing language switch must blend with glass cluster');
assert.match(home, /<WesalLauncher lang=\{lang\}/, 'Keep launch location beside language control');
assert.match(top, /<WesalLauncher lang=\{lang\}/, 'Keep launcher on school/admin pages');
assert.doesNotMatch(view, /\bt\('رسالة غير مقروءة'/, 'Translation function must not be shadowed by thread variable');

assert.doesNotMatch(home, /HelpCircle|hub_onboarding_seen|qul-header-guide|Onboarding Tour/, 'No onboarding button in main Home header');
assert.doesNotMatch(top, /HelpCircle|restartTour|hub_onboarding_seen|qul-header-guide|Guided tour/, 'No onboarding control for admins or managers');
assert.doesNotMatch(layout, /OnboardingTour/, 'The onboarding tour must never auto-start on platform load');
assert.doesNotMatch(glass, /qul-header-guide/, 'No unused tour control style in header glass');
assert.equal((home.match(/<WesalLauncher lang=\{lang\}/g)||[]).length, 1, 'One Wesal button in Home tools');
assert.equal((top.match(/<WesalLauncher lang=\{lang\}/g)||[]).length, 1, 'One Wesal button in manager/admin tools');
assert.match(glass, /\.qul-header-glass \.qul-language-action\s*\{[^}]*flex: 1 1 0%;/, 'Language button takes equal space');
assert.match(glass, /\.qul-header-glass \.wesal-launch\s*\{[^}]*flex: 1 1 0%;/, 'Wesal button takes equal space');
console.log('Wesal RTL/LTR, translation, tour removal and matched header checks passed.');
