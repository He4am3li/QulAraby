import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
execFileSync(process.execPath,['--check','public/penalty-3d-engine.js'],{stdio:'pipe'});
const setup=readFileSync('components/games/PenaltyEliteSetup.tsx','utf8');
const jersey=readFileSync('components/games/PenaltyJersey.tsx','utf8');
const adapter=readFileSync('components/games/PenaltyLive3D.tsx','utf8');
const engine=readFileSync('public/penalty-3d-engine.js','utf8');
const game=readFileSync('components/games/PenaltyShootout.tsx','utf8');
assert.match(setup,/AnimatePresence mode="wait"/,'Cinematic scene transitions');
assert.match(setup,/useReducedMotion/,'Motion accessibility');
assert.match(setup,/elite-stadium/,'Stadium backdrop');
assert.match(setup,/ELITE_CLUBS.map/,'Ten club identity rail');
assert.match(setup,/PenaltyJersey club=\{club\} number=\{player.number\}/,'Player shirt and number in lineup');
assert.match(jersey,/club\.crestUrl/,'Authentic crest on jersey illustration');
assert.match(jersey,/club\.id==='barcelona'/,'Club-specific Barcelona kit pattern');
assert.match(jersey,/club\.id==='juventus'/,'Club-specific Juventus kit stripes');
assert.match(jersey,/number/,'Player number on original-style team jersey');
assert.match(adapter,/onReady:/,'3D rig loading confirmation');
assert.match(adapter,/!failed\?'animate-spin'/,'Cinematic loading state');
assert.match(engine,/addNumberPanels\(a\)/,'3D player number decals');
assert.match(engine,/setKit\(options=\{\}\)/,'3D player and goalkeeper kits');
assert.doesNotMatch(engine,/for\(const a of actors\)a\.root\.add\(a\.fallback\.root\)/,'Geometric placeholder may never appear before rig');
assert.match(game,/keeperNumber:goalkeeper\?\.number/,'Goalkeeper must wear its own number');
assert.match(game,/kit=\{stadiumKit\}/,'Team kit changes between shots');
console.log('Penalty Elite console-style carousel, club shirts, animated transition, no geometric first-frame and dynamic 3D numbers: PASS');
