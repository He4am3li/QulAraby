import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';
const window = new Window();
for (const key of ['window','document','navigator','HTMLElement','Element','Node','Event']) Object.defineProperty(globalThis,key,{value:key==='window'?window:window[key],configurable:true});
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const React=await import('react');const {act}=React;const {createRoot}=await import('react-dom/client');
await mkdir('node_modules/.cache',{recursive:true});
await build({entryPoints:['components/CassetteLibrary.tsx'],outfile:'node_modules/.cache/cassette-library.mjs',bundle:true,platform:'node',format:'esm',packages:'external',loader:{'.css':'empty'}});
const {CassetteLibrary}=await import('../node_modules/.cache/cassette-library.mjs');
await build({entryPoints:['src/data/shelfCassettes.ts'],outfile:'node_modules/.cache/cassette-tapes.mjs',bundle:true,platform:'node',format:'esm'});
const {getShelfTapesForLevel}=await import('../node_modules/.cache/cassette-tapes.mjs');
const host=document.createElement('div');document.body.append(host);const root=createRoot(host),ref=React.createRef();
let selected;const tapes=getShelfTapesForLevel('beginner');
const render=async(busy=false)=>act(async()=>root.render(React.createElement(CassetteLibrary,{ref,tapes,activeTapeId:selected?.id||null,isPlaying:false,busy,onSelect:(t,event)=>{assert.equal(event.currentTarget.dataset.tapeId,t.id);selected=t;}})));
await render();assert.equal(host.querySelectorAll('[data-tape-id]').length,10);
assert.equal(host.querySelector('.qul-archive-footer'),null);
assert.ok(host.querySelector('.qul-archive-drawer[tabindex="0"]'));
await act(async()=>ref.current.selectTape(tapes[9].id));assert.equal(selected.id,tapes[9].id);
await render(true);assert.ok([...host.querySelectorAll('button')].every(b=>b.disabled));
await act(async()=>ref.current.selectTape(tapes[0].id));assert.equal(selected.id,tapes[9].id);
await act(async()=>root.unmount());
console.log('PASS: all tapes rendered, keyboard-accessible scroll region, next-tape selection, insertion lock');
