export const getStoryQuestions = (storyId: string, fallbackStory?: any): StoryQuestion[] => {
  if (STORY_QUESTIONS_MAP[storyId]) {
    return STORY_QUESTIONS_MAP[storyId];
  }
  if (fallbackStory) {
    return [
      {
        question: `ما القيمة التربوية الأساسية المستفادة من شريط "${fallbackStory.titleAr}"؟`,
        options: [
          fallbackStory.moralLessonAr,
          'الانتظار دون سعي أو عمل جاد',
          'الاهتمام بالمظاهر السطحية فقط'
        ],
        correctIndex: 0,
        explanation: fallbackStory.moralLessonAr
      },
      {
        question: `من خلال استماعك، إلى أي تصنيف ينتمي هذا الشريط الصوتي؟`,
        options: [fallbackStory.categoryAr, 'قصص خيالية مرعبة', 'أشعار فلكية قديمة'],
        correctIndex: 0,
        explanation: `ينتمي هذا الشريط إلى قسم ${fallbackStory.categoryAr}.`
      }
    ];
  }
  return [];
};
