/**
 * Returns clean direct English translation without any synthetic prefixes or labels
 */
export function getEnglishTranslation(arabicWord: string): string {
  const clean = arabicWord.replace(/[.,!?;:()،«»"ـ\s]/g, '').trim();
  if (ARABIC_ENGLISH_DICT[clean]) return ARABIC_ENGLISH_DICT[clean];

  // Try matching stripped prefixes (و, ف, ب, ل, ال, فال, وال, بال, كال)
  const prefixes = ['وال', 'فال', 'كال', 'بال', 'لل', 'ال', 'و', 'ف', 'ب', 'ل', 'ك', 'س'];
  for (const p of prefixes) {
    if (clean.startsWith(p) && clean.length > p.length + 1) {
      const stem = clean.slice(p.length);
      if (ARABIC_ENGLISH_DICT[stem]) {
        const prefixMeaning = p.includes('و') ? 'and ' : p.includes('ف') ? 'then ' : '';
        return prefixMeaning + ARABIC_ENGLISH_DICT[stem];
      }
    }
  }

  // Try suffix stripping (ها, هم, نا, كم, ه, ي)
  const suffixes = ['هما', 'كما', 'هم', 'هن', 'ها', 'نا', 'كم', 'ني', 'ه', 'ي'];
  for (const s of suffixes) {
    if (clean.endsWith(s) && clean.length > s.length + 2) {
      const stem = clean.slice(0, -s.length);
      if (ARABIC_ENGLISH_DICT[stem]) {
        return ARABIC_ENGLISH_DICT[stem] + ' (with pronoun)';
      }
    }
  }

  // Common root stems
  if (clean.includes('علم')) return 'knowledge / learning';
  if (clean.includes('كتب')) return 'writing / book';
  if (clean.includes('قرأ')) return 'reading / reciting';
  if (clean.includes('سمع')) return 'hearing / listening';
  if (clean.includes('شجر')) return 'trees / nature';
  if (clean.includes('عمل')) return 'work / endeavor';
  if (clean.includes('بيت')) return 'house / home';
  if (clean.includes('يوم')) return 'day / time';
  if (clean.includes('قال')) return 'said / spoke';
  if (clean.includes('حب')) return 'love / seeds';
  if (clean.includes('أرض')) return 'earth / land';
  if (clean.includes('ماء')) return 'water / life';
  if (clean.includes('نار')) return 'fire';
  if (clean.includes('خير')) return 'goodness / virtue';
  if (clean.includes('صبر')) return 'patience';
  if (clean.includes('ذهب')) return 'gold / precious';

  return 'Word in story';
}
